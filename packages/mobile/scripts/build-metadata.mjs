#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import { pathToFileURL } from 'node:url';
import { productIdentity } from '../../cezar/src/home/identity.ts';

/** Release inputs only. No preferences or browser data are read or copied. */
export function mobileMetadata({ rebrand, finalOldApp = false, storeUrl = '' } = {}) {
  if (rebrand !== undefined && !['on', 'off'].includes(rebrand)) throw new Error('--rebrand must be on or off');
  if (finalOldApp) {
    const url = new URL(storeUrl);
    if (url.protocol !== 'https:' || url.username || url.password) throw new Error('Supply an HTTPS store URL without credentials');
  } else if (storeUrl) {
    throw new Error('--store-url requires --final-old-app');
  }
  const selected = finalOldApp ? false : rebrand === undefined ? undefined : rebrand === 'on';
  return { ...productIdentity(selected), finalOldApp, storeUrl, moveDisplayName: productIdentity(true).displayName };
}

export function iosConfiguration(metadata) {
  return `// Generated by packages/mobile/scripts/build-metadata.mjs. Do not edit.
MOBILE_APP_ID = ${metadata.mobileAppId}
MOBILE_TEST_ID_PREFIX = ${metadata.desktopAppId}
MOBILE_DISPLAY_NAME = ${metadata.displayName}
MOBILE_MOVE_DISPLAY_NAME = ${metadata.moveDisplayName}
MOBILE_FINAL_OLD_APP = ${metadata.finalOldApp}
MOBILE_STORE_URL_BASE64 = ${Buffer.from(metadata.storeUrl).toString('base64')}
MOBILE_SWIFT_CONDITIONS = ${metadata.finalOldApp ? 'FINAL_OLD_APP' : ''}
`.replace(/ +$/gm, '');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const { values } = parseArgs({ options: {
      rebrand: { type: 'string' }, 'final-old-app': { type: 'boolean' },
      'store-url': { type: 'string' }, 'write-ios': { type: 'boolean' },
    } });
    const metadata = mobileMetadata({ rebrand: values.rebrand, finalOldApp: values['final-old-app'], storeUrl: values['store-url'] });
    if (values['write-ios']) writeFileSync(new URL('../ios/ProductIdentity.xcconfig', import.meta.url), iosConfiguration(metadata));
    console.log(JSON.stringify(metadata));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
